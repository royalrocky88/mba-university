/** Department filter options for `/faculty`, derived from the data. */
export const facultyDepartments = [...new Set(faculty.map((f) => f.department))].sort()

export function getFacultyBySlug(slug: string | undefined): Faculty | undefined {
  return faculty.find((f) => f.slug === slug)
}

export function getFacultyByDepartment(department: string): Faculty[] {
  if (department === 'All') return faculty
  return faculty.filter((f) => f.department === department)
}

/** Used on the programme detail page to show who actually teaches the specialisation. */
export function getFacultyForDepartment(department: string, limit = 3): Faculty[] {
  return faculty.filter((f) => f.department === department).slice(0, limit)
}
